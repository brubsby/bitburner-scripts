/**
 * Expected ticks a freshly-opened position keeps its sign: to the next
 * boundary, then geometric in cycles (survives each with 0.55).
 */
export function expectedHold(st) {
  const r = ticksToBoundary(st) ?? TICKS_PER_CYCLE / 2
  return r - 1 + (TICKS_PER_CYCLE * (1 - FLIP_CHANCE)) / FLIP_CHANCE
}

/**
 * Decide this tick's orders.
 *
 * `book`: {
 *   cash,          money the trader may spend right now (after budget.js)
 *   positions:     {sym: [long, longAvg, short, shortAvg]}  (getPosition)
 *   maxShares:     {sym: n}
 *   ask, bid:      {sym: price}
 *   canShort:      boolean — BitNode 8 or SF8.2 (sfgate.canShortStock)
 *   liquidate:     true -> sell everything (install pending, claim due)
 *   raiseCash:     dollars that must be freed into cash this tick (claim)
 * }
 * Returns { orders: [{sym, kind: 'sell'|'cover'|'buy'|'short', shares, why}],
 *           targets, diag }.
 */
export function decide(st, book) {
  const o = st.opt
  const diag = { phase: st.phase, t: st.t, toBoundary: ticksToBoundary(st), pre4S: !st.f4s }
  const syms = st.symbols
  const sells = []
  const buys = []

  if (book.liquidate) {
    for (const s of syms) {
      const [L, , Sh] = book.positions[s]
      if (L > 0) sells.push({ sym: s, kind: 'sell', shares: L, why: 'liquidate' })
      if (Sh > 0) sells.push({ sym: s, kind: 'cover', shares: Sh, why: 'liquidate' })
    }
    return { orders: sells, diag: { ...diag, liquidate: true } }
  }

  const hold = o.entryHorizon ?? expectedHold(st)
  const tb = ticksToBoundary(st)
  const pre4S = !st.f4s
  const k = (s) => (o.impactAware ? IMPACT_PER_MOVE / (SYMBOL_META[s]?.S ?? 60000) : 0)
  // Per-tick edge per $ of the n-th share on `side` when otlkMag is M,
  // including the damage our own trading does (each S shares cut M by 0.006).
  const marginal = (s, side, mv, M, n) => {
    const Meff = M > IMPACT_FLOOR ? Math.max(IMPACT_FLOOR, M - 2 * k(s) * n) : M
    return tickEdge(0.5 + (side === 'L' ? 1 : -1) * (Meff / 100), mv, side)
  }
  // Pre-4S, holding across an imminent boundary risks a flip we learn late.
  const flipPenalty = (e) => (pre4S && o.flipExit && tb !== null && tb <= 2 ? FLIP_CHANCE * 2 * e * o.detectLag : 0)

  // ---- read the book -----------------------------------------------------
  const info = {}
  let wealth = book.cash
  for (const s of syms) {
    const [L, , Sh, shAvg] = book.positions[s]
    const bid = book.bid[s]
    const ask = book.ask[s]
    const mid = (bid + ask) / 2
    const vL = L > 0 ? L * bid - COMMISSION : 0
    const vS = Sh > 0 ? Sh * (2 * shAvg - ask) - COMMISSION : 0
    wealth += vL + vS
    const f = forecastOf(st, s)
    const mv = volOf(st, s)
    const sd = forecastSd(st, s)
    info[s] = { L, Sh, bid, ask, mid, spread: (ask - bid) / (2 * mid), f, mv, sd, max: book.maxShares[s] }
  }
  diag.wealth = wealth
  let cash = book.cash - Math.max(0, book.raiseCash ?? 0) - Math.max(0, book.reserve ?? 0)

  // ---- 1. exits: a position whose expected edge (posterior MEAN) is now
  // against it is closed. Entry demands the lower bound; exit the mean —
  // the band between them is the hysteresis that keeps noise from trading.
  const held = [] // chunks of what stays held, for the swap step
  for (const s of syms) {
    const x = info[s]
    if (x.mv === null) continue
    for (const side of ['L', 'S']) {
      const n = side === 'L' ? x.L : x.Sh
      if (!(n > 0)) continue
      const M = (side === 'L' ? x.f - 0.5 : 0.5 - x.f) * 100 // signed toward this side
      const e = M > 0 ? marginal(s, side, x.mv, M, n / 2) : tickEdge(x.f, x.mv, side)
      const wrongShort = side === 'S' && !book.canShort
      if (!(e - flipPenalty(Math.abs(e)) / hold > 0) || wrongShort) {
        sells.push({ sym: s, kind: side === 'L' ? 'sell' : 'cover', shares: n, why: `exit ${side}: f=${x.f.toFixed(3)}${wrongShort ? ' (shorting not allowed)' : ''}` })
        cash += side === 'L' ? n * x.bid - COMMISSION : n * (2 * (book.positions[s][3]) - x.ask) - COMMISSION
        continue
      }
      // Held chunks, least valuable first when swapping.
      const SL = 4
      const step = Math.ceil(n / SL)
      for (let a = 0; a < n; a += step) {
        const m = Math.min(step, n - a)
        const eh = marginal(s, side, x.mv, M, a + m / 2)
        held.push({ s, side, n: m, score: eh * hold - flipPenalty(eh), px: side === 'L' ? x.bid : x.ask })
      }
    }
  }

  // ---- 2. candidates: new shares on the favoured side, valued at the lower
  // confidence bound, net of the round trip they must pay.
  const cands = []
  for (const s of syms) {
    const x = info[s]
    if (x.mv === null) continue
    const side = x.f >= 0.5 ? 'L' : 'S'
    if (side === 'S' && !book.canShort) continue
    const Mlcb = Math.abs(x.f - 0.5) * 100 - o.entryZ * x.sd * 100
    if (Mlcb < o.minEdge * 100) continue
    const have = side === 'L' ? x.L : x.Sh
    const other = side === 'L' ? x.Sh : x.L
    const soldOther = sells.some((q) => q.sym === s)
    const room = x.max - have - (soldOther ? 0 : other) // maxShares counts both sides
    if (room <= 0) continue
    const cap = o.maxFrac < 1 ? Math.min(room, Math.max(0, Math.floor((o.maxFrac * wealth) / x.mid) - have)) : room
    const SL = 8
    const step = Math.max(1, Math.ceil(cap / SL))
    for (let a = 0; a < cap; a += step) {
      const m = Math.min(step, cap - a)
      const e = marginal(s, side, x.mv, Mlcb, have + a + m / 2)
      if (!(e > 0)) break
      const score = e * hold - flipPenalty(e) - 2 * x.spread
      if (!(score > 0)) break
      cands.push({ s, side, n: m, score, px: side === 'L' ? x.ask : x.bid })
    }
  }
  cands.sort((p, q) => q.score - p.score)
  held.sort((p, q) => p.score - q.score)

  const want = {} // s|side -> shares to buy
  const trim = {} // s|side -> shares to sell
  let hi = 0
  // ---- 3a. a claim that is due (raiseCash/reserve above the cash we hold)
  // is paid by selling the weakest held chunks first.
  while (cash < 0 && hi < held.length) {
    const h = held[hi]
    const take = Math.min(h.n, Math.ceil((-cash + COMMISSION) / h.px))
    trim[`${h.s}|${h.side}`] = (trim[`${h.s}|${h.side}`] ?? 0) + take
    cash += take * h.px - COMMISSION
    h.n -= take
    if (h.n <= 0) hi++
  }
  diag.raised = Object.keys(trim).length > 0

  // ---- 3b. fill from free cash, then 4. swap out the weakest held chunks
  // while a candidate beats them by the switch margin.
  for (const c of cands) {
    let need = c.n
    while (need > 0) {
      const dollars = need * c.px
      if (cash >= c.px) {
        const n = Math.min(need, Math.floor(cash / c.px))
        want[`${c.s}|${c.side}`] = (want[`${c.s}|${c.side}`] ?? 0) + n
        cash -= n * c.px
        need -= n
        continue
      }
      // No free cash: displace the weakest held chunk if clearly better.
      const h = held[hi]
      if (!h || h.s === c.s || !(c.score - h.score > o.switchMargin)) break
      const take = Math.min(h.n, Math.ceil(dollars / h.px))
      trim[`${h.s}|${h.side}`] = (trim[`${h.s}|${h.side}`] ?? 0) + take
      cash += take * h.px
      h.n -= take
      if (h.n <= 0) hi++
    }
    if (need > 0 && cash < c.px && !(held[hi] && c.score - held[hi].score > o.switchMargin)) break
  }

  // ---- 5. orders, with commission and churn guards.
  for (const [key, n] of Object.entries(trim)) {
    const [s, side] = key.split('|')
    sells.push({ sym: s, kind: side === 'L' ? 'sell' : 'cover', shares: n, why: `switch out ${side}: f=${info[s].f.toFixed(3)}` })
  }
  let spend = book.cash - Math.max(0, book.raiseCash ?? 0) - Math.max(0, book.reserve ?? 0)
  for (const q of sells) {
    const x = info[q.sym]
    spend += q.kind === 'sell' ? q.shares * x.bid - COMMISSION : q.shares * (2 * book.positions[q.sym][3] - x.ask) - COMMISSION
  }
  const buyList = Object.entries(want)
    .map(([key, n]) => {
      const [s, side] = key.split('|')
      const x = info[s]
      const px = side === 'L' ? x.ask : x.bid
      const Mlcb = Math.abs(x.f - 0.5) * 100 - o.entryZ * x.sd * 100
      const have = side === 'L' ? x.L : x.Sh
      const e = marginal(s, side, x.mv, Mlcb, have + n / 2)
      return { s, side, n, px, gain: n * px * (e * hold - 2 * x.spread), e }
    })
    .sort((p, q) => q.gain - p.gain)
  for (const b of buyList) {
    const have = b.side === 'L' ? info[b.s].L : info[b.s].Sh
    // Commission: the buy and its eventual sale must be paid for.
    if (!(b.gain > 2 * COMMISSION * o.commissionCover)) continue
    // Churn: topping up an existing position by a sliver is not worth a trade.
    if (have > 0 && b.n < o.minTradeFrac * have) continue
    let n = b.n
    if (n * b.px + COMMISSION > spend) n = Math.floor((spend - COMMISSION) / b.px)
    if (!(n > 0) || n * b.px * (b.e * hold) < 2 * COMMISSION * o.commissionCover) continue
    buys.push({ sym: b.s, kind: b.side === 'L' ? 'buy' : 'short', shares: n, why: `${b.side} f=${info[b.s].f.toFixed(3)}±${info[b.s].sd.toFixed(3)} edge ${(b.e * 1e4).toFixed(2)}bp/tick` })
    spend -= n * b.px + COMMISSION
  }
  diag.cash = cash
  return { orders: [...sells, ...buys], diag }
}
