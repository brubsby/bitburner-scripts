// The stock trader's brain. Pure: no ns calls, free to import.
//
// stock.js feeds it one observation per market tick (ns.stock.nextUpdate) and
// executes the orders it returns. tools/sim/stocks/ runs the SAME functions
// against the game's own market code, which is where every constant below was
// chosen and where the claims in this header are measured (docs/stocks.md).
//
// ---------------------------------------------------------------------------
// THE MARKET, from ~/Repos/bitburner/src/StockMarket (v3.0.2)
//
//   StockMarket.ts:264-305  every 6s: one v = Math.random() SHARED by all 33
//                           stocks; av = v*mv/100; up (x(1+av)) with chance
//                           (50+otlkMag)/100 when bullish (b), down otherwise.
//   StockMarket.ts:223-236  every 75 ticks (one global counter, first length
//                           random 1..75) each stock flips b with chance 0.45 —
//                           its forecast f becomes 1-f.
//   Stock.ts:178-200        otlkMag drifts each tick by otlkMag*av toward the
//                           second-order forecast; the forecast is otherwise
//                           near-constant inside a cycle.
//   StockMarketHelpers.ts:463  each shareTxForMovement shares traded (either
//                           way) cut otlkMag by 0.006, floor 5. There is NO
//                           price impact in v3: the size limit on a position is
//                           maxShares and this forecast damage, nothing else.
//   Stock.ts:229-236        buy at ask = price(1+spread), sell at bid =
//                           price(1-spread); $100k commission per transaction.
//
// ---------------------------------------------------------------------------
// WHAT THIS DOES WITH IT
//
// 1. FORECAST. With 4S the forecast is read. Without it, it is ESTIMATED from
//    the up/down sequence each stock prints, which is an exact Bernoulli(f)
//    stream. The estimator knows the one structural fact that makes that
//    stream tractable: f only jumps at the global cycle boundary. So
//      - the boundary PHASE is learned once, jointly across all 33 stocks
//        (a flip in ~45% of them on the same tick is unmistakable), and
//      - per stock, the belief is a two-component Beta mixture that splits at
//        each boundary into "same" (0.55) and "flipped" (0.45) and lets the
//        next ticks decide which, instead of a sliding window that forgets
//        good data and learns flips late.
// 2. VOLATILITY. Never read (getVolatility is 2.5GB and 4S-only). The shared v
//    makes |ln(P_t/P_t-1)| = ln(1+v*mv/100) for every stock at once, so mv is
//    estimated from the price stream to a few percent within one cycle.
// 3. SIZING. No leverage exists, and Kelly's fraction for these walks is ~20x
//    capital, so the log-optimal policy is: be fully invested in the best
//    edges. The only limits are maxShares, the forecast damage our own
//    orders do (the marginal edge of the n-th share falls by 2*0.006*n/S), and
//    what the switch costs. So the portfolio is chosen greedily by MARGINAL
//    per-tick edge, where a held dollar competes at its edge and a new dollar
//    at its edge minus the round trip it has to pay.
// 4. SHORTS where the game allows them (BitNode 8 or SF8.2 — the caller says).

