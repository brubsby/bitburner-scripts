const lnGamma = (() => {
  // Lanczos, g=7 — plenty for Beta-binomial ratios at counts <= a few hundred.
  const c = [0.99999999999980993, 676.5203681218851, -1259.1392167224028, 771.32342877765313, -176.61502916214059, 12.507343278686905, -0.13857109526572012, 9.9843695780195716e-6, 1.5056327351493116e-7]
  return function lg(x) {
    if (x < 0.5) return Math.log(Math.PI / Math.sin(Math.PI * x)) - lg(1 - x)
    x -= 1
    let a = c[0]
    const t = x + 7.5
    for (let i = 1; i < 9; i++) a += c[i] / (x + i)
    return 0.5 * Math.log(2 * Math.PI) + (x + 0.5) * Math.log(t) - t + Math.log(a)
  }
})()
export const lnBeta = (a, b) => lnGamma(a) + lnGamma(b) - lnGamma(a + b)

/**
 * log LR of "the stock flipped between window 1 and window 2" against "it did
 * not", each window's ups k of n, uniform prior on f. Under a flip, window 2's
 * downs are window 1's ups.
 */
export function flipLogLR(k1, n1, k2, n2) {
  const flip = lnBeta(1 + k1 + (n2 - k2), 1 + (n1 - k1) + k2)
  const same = lnBeta(1 + k1 + k2, 1 + (n1 - k1) + (n2 - k2))
  return flip - same
}

/**
 * Expected one-tick return of a position, from StockMarket.ts:293-300: the
 * price goes x(1+av) with chance f, /(1+av) otherwise; av = v*mv, v ~ U(0,1)
 * (mv as a fraction). E[av] = mv/2, E[av^2] = mv^2/3. Long gains the price
 * move; a short gains its negative (BuyingAndSelling/StockMarketHelpers:450).
 */
export function tickEdge(f, mv, side = 'L') {
  const ea = mv / 2
  const ea2 = (mv * mv) / 3
  const long = (2 * f - 1) * ea + (1 - f) * ea2
  return side === 'L' ? long : -long
}

