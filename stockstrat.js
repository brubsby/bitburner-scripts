/**
 * `symbols`: the market's symbols (ns.stock.getSymbols()). `o`: DEFAULTS
 * overrides. `o.phase`: a known phase (tests/harness), else learned.
 */
export function newState(symbols, o = {}) {
  const opt = { ...DEFAULTS, ...o }
  const st = {
    opt,
    symbols: [...symbols],
    t: 0, // ticks observed
    phase: Number.isInteger(o.phase) ? o.phase : null, // t mod 75 of the first post-flip tick
    phaseFixed: Number.isInteger(o.phase),
    phaseScore: new Array(TICKS_PER_CYCLE).fill(0),
    phaseVotes4S: new Array(TICKS_PER_CYCLE).fill(0),
    lastPrice: {},
    hist: {}, // per symbol: array of 1/0 (up/down), newest last, bounded
    comps: {}, // per symbol: [{w,a,b}]
    absLnSum: {}, // per symbol: sum |ln ratio| (volatility)
    absLnN: 0,
    f4s: null, // last 4S forecasts when available
    f4sPrev: null,
    missed: 0,
  }
  for (const s of symbols) {
    st.hist[s] = []
    st.comps[s] = [{ w: 1, a: opt.prior, b: opt.prior }]
    st.absLnSum[s] = 0
  }
  if (opt.estimator === 'hmm') st.hmm = newHmm(symbols.length, st.phaseFixed ? [st.phase] : null)
  return st
}

// ---------------------------------------------------------------------------
// THE HMM ESTIMATOR (pre-4S)
//
// The hidden state of one stock is its forecast f, on a grid f = i/100. Per
// tick: (a) at a cycle boundary f -> 1-f with chance 0.45 (StockMarket.ts:
// 228-231), (b) a small diffusion for otlkMag drift (Stock.ts:178-200 — about
// otlkMag*av per tick, a fraction of a grid step), (c) the observation: up with
// chance f. That is an exact HMM given the boundary PHASE, which is shared by
// all 33 stocks and unknown, so there is one filter bank per candidate phase
// (75), each accumulating the log-likelihood of every stock's stream; the
// phase posterior is their softmax, and banks are pruned as it concentrates
// (after a few cycles only the true phase is left: 33 x 101 per tick).
// Cost before pruning: 75 x 33 x 101 multiply-adds per 6s tick — a few ms.

const GRID = 101
const FGRID = Float64Array.from({ length: GRID }, (_, i) => i / (GRID - 1))

/**
 * The stationary distribution of |f-0.5|*100 in bins of 5, measured on the
 * game's own market (tools/sim/stocks/fprior.mjs: 20 seeds, ticks 3000-30000).
 * Most stocks sit at otlkMag 5-10: the drift is x10 below 5 (Stock.ts via
 * StockMarket.ts:308-313), which empties the band near 0.5. A uniform prior
 * instead made a 4-tick streak look like f~0.8 and the phase filter lock onto
 * spurious boundaries within 6 ticks.
 */
export const F_PRIOR_BINS = [0.054, 0.5879, 0.2185, 0.0845, 0.0384, 0.0083, 0.0032, 0.002, 0.0017, 0.0014]
const PRIOR = (() => {
  const bin = (i) => Math.min(9, Math.floor(Math.abs(i - 50) / 5))
  const count = new Array(10).fill(0)
  for (let i = 0; i < GRID; i++) count[bin(i)]++
  const p = Float64Array.from({ length: GRID }, (_, i) => F_PRIOR_BINS[bin(i)] / count[bin(i)])
  const z = p.reduce((a, b) => a + b, 0)
  return p.map((x) => x / z)
})()

function newHmm(nSym, phases = null) {
  const alive = phases ?? Array.from({ length: TICKS_PER_CYCLE }, (_, i) => i)
  const banks = new Map()
  for (const ph of alive) {
    const P = new Float64Array(nSym * GRID)
    for (let j = 0; j < nSym; j++) P.set(PRIOR, j * GRID)
    banks.set(ph, { P, logL: 0 })
  }
  return { banks, post: new Map(alive.map((ph) => [ph, 1 / alive.length])) }
}

function observeHmm(st, ups) {
  const H = st.hmm
  const n = st.symbols.length
  const d = st.opt.diffusion
  const tmp = new Float64Array(GRID)
  for (const [ph, bank] of H.banks) {
    const P = bank.P
    const boundary = mod(st.t - ph, TICKS_PER_CYCLE) === 0
    let ll = 0
    for (let j = 0; j < n; j++) {
      const o = j * GRID
      // (a) flip at this bank's boundary, (b) diffusion
      for (let i = 0; i < GRID; i++) {
        let p = P[o + i]
        if (boundary) p = (1 - FLIP_CHANCE) * p + FLIP_CHANCE * P[o + GRID - 1 - i]
        tmp[i] = p
      }
      let z = 0
      const up = ups[j]
      for (let i = 0; i < GRID; i++) {
        const left = i > 0 ? tmp[i - 1] : tmp[i]
        const right = i < GRID - 1 ? tmp[i + 1] : tmp[i]
        const p = (1 - 2 * d) * tmp[i] + d * left + d * right
        // (c) observation
        const q = p * (up ? FGRID[i] : 1 - FGRID[i])
        P[o + i] = q
        z += q
      }
      if (!(z > 0)) {
        for (let i = 0; i < GRID; i++) P[o + i] = PRIOR[i]
        ll += Math.log(0.5)
        continue
      }
      for (let i = 0; i < GRID; i++) P[o + i] /= z
      ll += Math.log(z)
    }
    bank.logL += ll
  }
  // Phase posterior (uniform prior over the banks that were ever alive).
  let mx = -Infinity
  for (const b of H.banks.values()) if (b.logL > mx) mx = b.logL
  let Z = 0
  for (const b of H.banks.values()) Z += Math.exp(b.logL - mx)
  H.post = new Map()
  for (const [ph, b] of H.banks) H.post.set(ph, Math.exp(b.logL - mx) / Z)
  for (const [ph, w] of H.post) {
    if (w < st.opt.phasePrune && H.banks.size > 1) {
      H.banks.delete(ph)
      H.post.delete(ph)
    }
  }
  // Rebase log-likelihoods so they never overflow.
  for (const b of H.banks.values()) b.logL -= mx
}

function hmmMoments(st, s) {
  const H = st.hmm
  const j = st.symbols.indexOf(s)
  let m = 0
  let m2 = 0
  for (const [ph, b] of H.banks) {
    const w = H.post.get(ph) ?? 0
    if (w < 1e-9) continue
    const o = j * GRID
    for (let i = 0; i < GRID; i++) {
      const p = b.P[o + i] * w
      m += p * FGRID[i]
      m2 += p * FGRID[i] * FGRID[i]
    }
  }
  return { m, sd: Math.sqrt(Math.max(0, m2 - m * m)) }
}

/** The most probable phase and its posterior (hmm estimator). */
export function hmmPhase(st) {
  if (!st.hmm) return null
  let best = null
  for (const [ph, w] of st.hmm.post) if (!best || w > best.w) best = { phase: ph, w }
  return best
}

const HIST_MAX = 160

/**
 * Feed one market tick. `prices`: {sym: price} read after the tick;
 * `forecasts`: {sym: f} when 4S TIX API is owned, else null/undefined.
 * Returns nothing; mutates `st`.
 */
export function observe(st, prices, forecasts = null) {
  const o = st.opt
  const first = Object.keys(st.lastPrice).length === 0
  if (first) {
    for (const s of st.symbols) st.lastPrice[s] = prices[s]
    if (forecasts) st.f4s = { ...forecasts }
    return
  }
  // A tick in which NO price moved means the caller read twice between
  // updates; do not count it (every tick moves every price: av > 0 a.s.).
  let moved = 0
  for (const s of st.symbols) if (prices[s] !== st.lastPrice[s]) moved++
  if (moved === 0) {
    st.missed++
    return
  }
  const t = st.t + 1
  st.t = t
  const boundaryNow = st.phase !== null && mod(t - st.phase, TICKS_PER_CYCLE) === 0

  let lnSum = 0
  const ups = new Uint8Array(st.symbols.length)
  let jj = 0
  for (const s of st.symbols) {
    const p = prices[s]
    const r = Math.log(p / st.lastPrice[s])
    st.lastPrice[s] = p
    const up = r > 0 ? 1 : 0
    ups[jj++] = up
    st.absLnSum[s] += Math.abs(r)
    lnSum += Math.abs(r)
    const h = st.hist[s]
    h.push(up)
    if (h.length > HIST_MAX) h.shift()

    // Belief update. At a known boundary the belief splits first.
    let comps = st.comps[s]
    if (st.phase !== null) {
      if (boundaryNow) comps = splitAtBoundary(collapse(comps))
    } else {
      // No phase yet: a single Beta with bounded memory (a window).
      comps = [collapse(comps)]
      capCount(comps[0], o.preWindow)
    }
    for (const c of comps) {
      const m = c.a / (c.a + c.b)
      c.w *= up ? m : 1 - m
      if (up) c.a += 1
      else c.b += 1
      capCount(c, o.maxCount)
    }
    normalise(comps)
    st.comps[s] = comps.filter((c) => c.w > 1e-6)
  }
  st.absLnN++
  // The filter runs with or without 4S: when 4S is lost (it never is within a
  // node) or before it is bought, the phase is already known.
  if (st.hmm && !forecasts) observeHmm(st, ups)

  // Phase evidence from the direction streams: score the candidate boundary
  // `phaseWin` ticks back, now that the window after it is complete.
  const W = o.phaseWin
  const h0 = st.hist[st.symbols[0]]
  if (h0.length >= 2 * W) {
    const tau = t - W + 1 // candidate: first tick of the after-window
    let score = 0
    for (const s of st.symbols) {
      const h = st.hist[s]
      const n = h.length
      let k1 = 0
      let k2 = 0
      for (let i = n - 2 * W; i < n - W; i++) k1 += h[i]
      for (let i = n - W; i < n; i++) k2 += h[i]
      const lr = flipLogLR(k1, W, k2, W)
      score += Math.log(1 - FLIP_CHANCE + FLIP_CHANCE * Math.exp(Math.min(lr, 50)))
    }
    st.phaseScore[mod(tau, TICKS_PER_CYCLE)] += score
  }

  // With 4S a flip is visible directly: f -> 1-f on the boundary tick.
  if (forecasts) {
    st.f4sPrev = st.f4s
    st.f4s = { ...forecasts }
    if (st.f4sPrev) {
      let flips = 0
      for (const s of st.symbols) {
        const a = st.f4sPrev[s] - 0.5
        const b = st.f4s[s] - 0.5
        if (Math.abs(a) > 0.03 && a * b < 0 && Math.abs(a + b) < 0.02) flips++
      }
      if (flips >= 3) st.phaseVotes4S[mod(t, TICKS_PER_CYCLE)] += flips
    }
  }
  // Re-decided every tick, not locked: an early, marginal lock on a phase a
  // tick or two off (measured: 3 of 4 seeds) is corrected as evidence grows.
  if (!st.phaseFixed) {
    if (st.hmm && !forecasts) {
      const b = hmmPhase(st)
      st.phase = b && b.w >= st.opt.phaseTrust ? b.phase : st.phase
    } else {
      const p = decidePhase(st)
      if (p !== null) st.phase = p
    }
  }
}

function decidePhase(st) {
  // 4S votes: two boundaries agreeing is decisive.
  let best4 = -1
  let bi4 = -1
  for (let i = 0; i < TICKS_PER_CYCLE; i++) if (st.phaseVotes4S[i] > best4) (best4 = st.phaseVotes4S[i]), (bi4 = i)
  if (best4 >= 6) return bi4
  const sc = st.phaseScore
  let bi = 0
  for (let i = 1; i < TICKS_PER_CYCLE; i++) if (sc[i] > sc[bi]) bi = i
  let second = -Infinity
  for (let i = 0; i < TICKS_PER_CYCLE; i++) {
    const d = Math.min(mod(i - bi, TICKS_PER_CYCLE), mod(bi - i, TICKS_PER_CYCLE))
    if (d > 3 && sc[i] > second) second = sc[i]
  }
  if (sc[bi] > 0 && sc[bi] - second > st.opt.phaseMargin) {
    // The windowed score peaks within a tick or two of the truth; refine to
    // the neighbour with the largest score.
    return bi
  }
  return null
}

const mod = (a, n) => ((a % n) + n) % n

function capCount(c, cap) {
  const n = c.a + c.b
  if (n > cap) {
    c.a *= cap / n
    c.b *= cap / n
  }
}
function normalise(comps) {
  const z = comps.reduce((s, c) => s + c.w, 0)
  if (!(z > 0)) {
    for (const c of comps) c.w = 1 / comps.length
    return
  }
  for (const c of comps) c.w /= z
}
/** Moment-match a Beta mixture to one Beta, keeping the total count. */
function collapse(comps) {
  if (comps.length === 1) return { w: 1, a: comps[0].a, b: comps[0].b }
  let mean = 0
  let n = 0
  for (const c of comps) {
    mean += c.w * (c.a / (c.a + c.b))
    n += c.w * (c.a + c.b)
  }
  // If one component dominates, keep it as it is (the mixture is unimodal).
  const top = comps.reduce((x, c) => (c.w > x.w ? c : x))
  if (top.w > 0.9) return { w: 1, a: top.a, b: top.b }
  return { w: 1, a: mean * n, b: (1 - mean) * n }
}
function splitAtBoundary(c) {
  return [
    { w: 1 - FLIP_CHANCE, a: c.a, b: c.b },
    { w: FLIP_CHANCE, a: c.b, b: c.a },
  ]
}

/** Posterior mean forecast for a symbol (4S when present). */
export function forecastOf(st, s) {
  if (st.f4s && typeof st.f4s[s] === 'number') return st.f4s[s]
  if (st.hmm) return hmmMoments(st, s).m
  const comps = st.comps[s]
  let m = 0
  for (const c of comps) m += c.w * (c.a / (c.a + c.b))
  return m
}

/** Posterior standard deviation of the forecast (0 with 4S). */
export function forecastSd(st, s) {
  if (st.f4s && typeof st.f4s[s] === 'number') return 0
  if (st.hmm) return hmmMoments(st, s).sd
  let m = 0
  let m2 = 0
  for (const c of st.comps[s]) {
    const n = c.a + c.b
    const mu = c.a / n
    const v = (c.a * c.b) / (n * n * (n + 1))
    m += c.w * mu
    m2 += c.w * (v + mu * mu)
  }
  return Math.sqrt(Math.max(0, m2 - m * m))
}

/** Volatility estimate (fraction): E|ln(1+av)| ~ E[av] = mv/2. */
export function volOf(st, s) {
  if (!st.absLnN) return null
  return (2 * st.absLnSum[s]) / st.absLnN
}

/** Ticks until the next boundary (1..75), or null when the phase is unknown. */
export function ticksToBoundary(st) {
  if (st.phase === null) return null
  // The next tick is st.t+1; it is a boundary when (t - phase) % 75 === 0.
  return mod(st.phase - (st.t + 1), TICKS_PER_CYCLE) + 1
}

